export const getDistrictsForState = (state) => {
  if (!state) return [];
  return INDIAN_STATES_AND_DISTRICTS[state] || [];
};

/**
 * Checks if a business address matches the selected state and/or district.
 * Inspects both `business.addressDetails` (structured) and `business.address` (text).
 */
export const matchBusinessLocation = (business, selectedState, selectedDistrict) => {
  if (!selectedState && !selectedDistrict) return true;
  if (!business) return false;

  const addrDetails = business.addressDetails || {};
  const fullAddress = (business.address || '').toLowerCase();
  const stateStr = (addrDetails.state || '').toLowerCase();
  const cityStr = (addrDetails.city || '').toLowerCase();

  if (selectedState) {
    const sLower = selectedState.toLowerCase();
    const stateMatches = stateStr.includes(sLower) || fullAddress.includes(sLower);
    if (!stateMatches) return false;
  }

  if (selectedDistrict) {
    const dLower = selectedDistrict.toLowerCase();
    // Some district names may include qualifiers like "Chennai" or "Kochi (Ernakulam)"
    const cleanDistrict = dLower.replace(/\s*\(.*?\)\s*/g, '').trim();
    const districtMatches =
      cityStr.includes(cleanDistrict) ||
      fullAddress.includes(cleanDistrict) ||
      (dLower.includes('(') && fullAddress.includes(dLower.match(/\((.*?)\)/)?.[1] || ''));
    if (!districtMatches) return false;
  }

  return true;
};

